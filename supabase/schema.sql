-- Keys99 CRM uses the existing public.enquiries table as its leads table (no extra tables).
-- Applied to the "Housing mantra enquiries" Supabase project. Safe to run once.

-- CRM fields (nullable or defaulted, so the landing-page insert keeps working).
alter table public.enquiries
  add column if not exists status        text  not null default 'New',
  add column if not exists follow_up     timestamptz,
  add column if not exists budget        text,
  add column if not exists location      text,
  add column if not exists property_type text,
  add column if not exists bhk           text,
  add column if not exists priority      text,
  add column if not exists notes         text,
  add column if not exists activities    jsonb not null default '[]'::jsonb;

alter table public.enquiries
  add constraint enquiries_status_check
  check (status in ('New','Contacted','Interested','Qualified','Site Visit','Negotiation','Booked','Lost'));

create index if not exists enquiries_status_idx     on public.enquiries (status);
create index if not exists enquiries_created_at_idx on public.enquiries (created_at desc);

-- Signed-in CRM users can read, add and update enquiries (no delete).
-- The existing "Allow anonymous enquiry insert" policy for the landing page is untouched.
create policy "CRM users can read enquiries"   on public.enquiries for select to authenticated using (true);
create policy "CRM users can update enquiries" on public.enquiries for update to authenticated using (true) with check (true);
create policy "CRM users can insert enquiries" on public.enquiries for insert to authenticated with check (true);

-- Why a lead was lost (used by "Mark as Lost" / "Mark as Spam").
alter table public.enquiries add column if not exists lost_reason text;

-- Site visits scheduled for a lead.
create table if not exists public.site_visits (
  id          bigint generated by default as identity primary key,
  enquiry_id  bigint not null references public.enquiries(id) on delete restrict,
  project     text,
  visit_at    timestamptz not null,
  status      text not null default 'Scheduled' check (status in ('Scheduled','Confirmed','Completed','Cancelled')),
  notes       text,
  created_by  text,
  created_at  timestamptz not null default now()
);
create index if not exists site_visits_enquiry_idx on public.site_visits (enquiry_id);
create index if not exists site_visits_visit_at_idx on public.site_visits (visit_at);

-- Bookings (deals) and the brokerage commission earned on them.
-- on delete restrict: an enquiry with money records cannot be deleted by accident.
create table if not exists public.bookings (
  id                bigint generated by default as identity primary key,
  enquiry_id        bigint not null references public.enquiries(id) on delete restrict,
  project           text,
  developer         text,
  booking_date      date not null default current_date,
  booking_value     numeric(14,2) not null default 0 check (booking_value >= 0),
  agreement_rate    numeric(5,2)  not null default 0 check (agreement_rate >= 0 and agreement_rate <= 100),
  commission_amount numeric(14,2) not null default 0 check (commission_amount >= 0),
  commission_status text not null default 'Pending' check (commission_status in ('Pending','Received')),
  received_on       date,
  notes             text,
  created_by        text,
  created_at        timestamptz not null default now()
);
create index if not exists bookings_enquiry_idx on public.bookings (enquiry_id);
create index if not exists bookings_date_idx on public.bookings (booking_date);

alter table public.site_visits enable row level security;
alter table public.bookings    enable row level security;
create policy "CRM users full access" on public.site_visits for all to authenticated using (true) with check (true);
create policy "CRM users full access" on public.bookings    for all to authenticated using (true) with check (true);
