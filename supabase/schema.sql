-- The registered project a lead's project text refers to (exact name first, then prefix, like the old team rule)
create or replace function public.project_for_name(p_name text) returns bigint
language sql stable security definer set search_path = '' as $$
  select p.id from public.projects p
  where length(public.norm_project(p.name)) >= 3 and length(public.norm_project(p_name)) >= 3
    and (public.norm_project(p.name) = public.norm_project(p_name)
         or public.norm_project(p_name) like public.norm_project(p.name) || '%'
