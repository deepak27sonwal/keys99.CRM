-- Auto-assign now uses the detailed rule and records why
create or replace function public.auto_assign_enquiry() returns trigger
language plpgsql security definer set search_path = '' as $$
declare on_ boolean; a record; has_mgr boolean;
begin
  select coalesce(value = 'true'::jsonb, false) into on_ from public.app_settings where key = 'auto_assign';
  if not coalesce(on_, false) then return new; end if;
  perform pg_advisory_xact_lock(727001);
  select * into a from public.assignee_detail(new.project);
  if a.id is null then return new; end if;
  has_mgr := new.manager_name is not null and new.manager_name not in ('null'::jsonb, '""'::jsonb, '[]'::jsonb);
  if not a.matched and has_mgr then return new; end if;
  new.manager_name := to_jsonb(a.name);
  new.manager_email := case when a.email is null then null else to_jsonb(a.email) end;
  new.activities := coalesce(new.activities, '[]'::jsonb) || jsonb_build_array(jsonb_build_object(
    'at', now(), 'by', 'Auto-assign', 'type', 'doc', 'title', 'Auto-assigned',
    'description', 'Assigned to ' || a.name || ' · ' || a.reason));
  update public.team_members set last_assigned_at = clock_timestamp() where team_members.id = a.id;
  return new;
exception when others then
  raise warning 'auto_assign_enquiry failed: %', sqlerrm;
  return new;
end $$;

-- A connected form / campaign decides the project of every NEW lead that comes from it (runs before auto-assign)
create or replace function public.route_source_to_project() returns trigger
language plpgsql security definer set search_path = '' as $$
declare s record; p record;
begin
  select ps.id, ps.project_id, ps.kind, ps.label into s from public.project_sources ps
   where (ps.kind = 'meta_form' and new.meta_form_id is not null and ps.ref_id = new.meta_form_id)
      or (ps.kind = 'meta_campaign' and new.meta_campaign_id is not null and ps.ref_id = new.meta_campaign_id)
   order by (ps.kind = 'meta_form') desc limit 1;
  if not found then return new; end if;
  select * into p from public.projects where projects.id = s.project_id;
  if not found then return new; end if;
  new.project := p.name;
  if p.developer is not null and (new.developer is null or length(trim(new.developer)) = 0) then new.developer := p.developer; end if;
  new.activities := coalesce(new.activities, '[]'::jsonb) || jsonb_build_array(jsonb_build_object(
    'at', now(), 'by', 'Project routing', 'type', 'doc', 'title', 'Project set',
    'description', 'Project set to ' || p.name || ' from the connected ' || case s.kind when 'meta_form' then 'form' else 'campaign' end || coalesce(' "' || s.label || '"', '')));
  return new;
exception when others then
  raise warning 'route_source_to_project failed: %', sqlerrm;
  return new;
end $$;
revoke all on function public.route_source_to_project() from public, anon, authenticated;
create or replace trigger enquiries_a_source_project before insert on public.enquiries for each row execute function public.route_source_to_project();

