-- Who gets the next lead for this project, and why. No side effects.
create or replace function public.assignee_detail(p_project text)
returns table (id bigint, name text, email text, matched boolean, reason text)
language plpgsql stable security definer set search_path = '' as $$
declare
  n text := public.norm_project(p_project); pid bigint; pr record; r record;
  mode text := 'round_robin'; fb text := 'rm_pool';
  day0 timestamptz := (date_trunc('day', now() at time zone 'Asia/Kolkata')) at time zone 'Asia/Kolkata';
  n_all integer := 0;
begin
  if length(n) >= 3 then
    pid := public.project_for_name(p_project);
    if pid is not null then select * into pr from public.projects where projects.id = pid; mode := pr.distribution; fb := pr.fallback; end if;
    if mode = 'manual' then return query select null::bigint, null::text, null::text, true, 'manual distribution: leads for this project stay unassigned'::text; return; end if;
    select c.id, c.name, c.email, c.w, c.today, c.wk, c.cap, c.n_all into r from (
      select m.id, m.name, m.email, m.last_assigned_at, m.daily_cap as cap, coalesce(pm.weight, 1) as w,
             (select count(*) from public.enquiries e where e.manager_name = to_jsonb(m.name) and e.created_at >= day0) as today,
             (select count(*) from public.enquiries e where e.manager_name = to_jsonb(m.name) and e.created_at >= now() - interval '7 days'
                and (case when pid is not null then public.project_for_name(e.project) = pid
                          else (public.norm_project(e.project) like n || '%' or n like public.norm_project(e.project) || '%') and length(public.norm_project(e.project)) >= 3 end)) as wk,
             count(*) over () as n_all
      from public.team_members m
      left join public.project_members pm on pm.member_id = m.id and pm.project_id = pid
      where m.status = 'Active' and coalesce(pm.paused, false) = false
        and (pm.project_id is not null
             or exists (select 1 from unnest(m.projects) pr2 where length(public.norm_project(pr2)) >= 3
                          and (n like public.norm_project(pr2) || '%' or public.norm_project(pr2) like n || '%')))
    ) c
    where c.cap is null or c.today < c.cap
    order by (case when mode = 'weighted' then c.wk::numeric / c.w else 0 end), c.last_assigned_at nulls first, c.id limit 1;
    if found then
      return query select r.id, r.name, r.email, true,
        (case when mode = 'weighted' then 'weighted share (weight ' || r.w || ', ' || r.wk || ' leads this week)' else 'round-robin (longest waiting)' end
         || ', ' || r.today || ' today' || case when r.cap is not null then ' of ' || r.cap else '' end)::text;
      return;
    end if;
    -- nobody available: say why, then use the project's fallback
    select count(*) into n_all from public.team_members m left join public.project_members pm on pm.member_id = m.id and pm.project_id = pid
      where m.status = 'Active' and coalesce(pm.paused, false) = false and (pm.project_id is not null
        or exists (select 1 from unnest(m.projects) pr2 where length(public.norm_project(pr2)) >= 3 and (n like public.norm_project(pr2) || '%' or public.norm_project(pr2) like n || '%')));
    if fb = 'unassigned' then return query select null::bigint, null::text, null::text, false, (case when n_all > 0 then 'everyone on the team is at their daily cap' else 'no team member is assigned to this project' end || '; left unassigned')::text; return; end if;
  end if;
  select m.id, m.name, m.email into r from public.team_members m
   where m.status = 'Active' and m.kind = 'rm'
     and (m.daily_cap is null or (select count(*) from public.enquiries e where e.manager_name = to_jsonb(m.name) and e.created_at >= day0) < m.daily_cap)
   order by m.last_assigned_at nulls first, m.id limit 1;
  if found then
    return query select r.id, r.name, r.email, false, (case when length(n) < 3 then 'no project on the lead: shared relationship-manager round-robin' when n_all > 0 then 'team at daily cap: shared relationship-manager round-robin' else 'no team for this project: shared relationship-manager round-robin' end)::text;
  end if;
end $$;
revoke all on function public.assignee_detail(text) from public, anon;
grant execute on function public.assignee_detail(text) to authenticated;

